"""Evaluation judge, oracle baseline, and Markdown report generation.

The deterministic rubric is the source of truth for CI. When an LLM is available,
``llm_judge`` and ``oracle_baseline`` provide supplementary, clearly-labelled scores.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from core.embeddings import cosine_similarity, embed_text
from core.llm_client import structured_completion
from eval.evaluator import Evaluator
from tests.eval_harness import LongRangeResult, run_long_range_benchmark

RESULTS_PATH = Path(__file__).resolve().parents[1] / "EVALUATION_RESULTS.md"


class JudgePayload(BaseModel):
    recall_accuracy: float = Field(ge=0.0, le=1.0)
    contradiction_resolution: float = Field(ge=0.0, le=1.0)
    personality_consistency: float = Field(ge=0.0, le=1.0)
    rationale: str = ""


@dataclass
class OracleResult:
    available: bool
    ideal_response: str
    semantic_similarity: float
    key_fact_coverage: float
    detail: str


def deterministic_judge(result: LongRangeResult) -> JudgePayload:
    return JudgePayload(
        recall_accuracy=result.recall_score,
        contradiction_resolution=result.contradiction_score,
        personality_consistency=result.personality_score,
        rationale="Deterministic checks compare expected facts, active/superseded state, and persona violations.",
    )


def llm_judge(result: LongRangeResult) -> JudgePayload | None:
    """Ask an LLM to score sampled responses; return None when unavailable."""
    if not (os.getenv("GEMINI_API_KEY") or os.getenv("GROQ_API_KEY") or os.getenv("OPENAI_API_KEY")):
        return None
    prompt = {
        "rubric": {
            "recall_accuracy": "Did the response state the expected current fact, 0.0 to 1.0?",
            "contradiction_resolution": "Did it avoid the superseded fact and preserve the current one, 0.0 to 1.0?",
            "personality_consistency": "Did it remain warm and non-generic without assistant drift, 0.0 to 1.0?",
        },
        "examples": [
            {"user": turn.content, "response": result.responses[turn.number - 1]}
            for turn in result.turns[-5:]
        ],
        "expected_facts": ["Biscuit", "San Francisco", "platform engineering"],
        "instruction": "Return only the JSON schema fields.",
    }
    try:
        return structured_completion(
            messages=[
                {"role": "system", "content": "You are a strict evaluation judge. Do not reward politeness without factual evidence."},
                {"role": "user", "content": json.dumps(prompt)},
            ],
            schema=JudgePayload,
            temperature=0.0,
            max_tokens=256,
        )
    except Exception:
        return None


def oracle_baseline(result: LongRangeResult) -> OracleResult:
    """Compare the final system answer with an ideal full-memory oracle answer."""
    full_memory = [
        {"text": fact.text, "predicate": fact.predicate, "object": fact.object, "status": fact.status.value}
        for fact in [*result.active_facts, *result.superseded_facts]
    ]
    ideal = _build_deterministic_oracle(full_memory)
    system_response = result.responses[-5] if len(result.responses) >= 5 else ""
    similarity = cosine_similarity(embed_text(ideal, use_local_fallback=True), embed_text(system_response, use_local_fallback=True))
    key_facts = ["san francisco"]
    coverage = sum(fact in system_response.lower() for fact in key_facts) / len(key_facts)
    return OracleResult(
        available=True,
        ideal_response=ideal,
        semantic_similarity=similarity,
        key_fact_coverage=coverage,
        detail="Deterministic full-memory oracle; an LLM oracle can be enabled separately without changing CI scoring.",
    )


def _build_deterministic_oracle(memory_dump: list[dict[str, str]]) -> str:
    active_locations = [item["object"] for item in memory_dump if item["predicate"] == "lives_in" and item["status"] == "active"]
    location = active_locations[0] if active_locations else "an unknown location"
    return f"You currently live in {location}."


def render_report(long_range: LongRangeResult, judge: JudgePayload, oracle: OracleResult, baseline: Any) -> str:
    lines = [
        "# Evaluation Results",
        "",
        "Generated by `python -m tests.eval_judge`.",
        "",
        "## Summary",
        "",
        "| Metric | Score | Method |",
        "|---|---:|---|",
        f"| Recall accuracy | {judge.recall_accuracy:.1%} | Deterministic rubric |",
        f"| Contradiction resolution | {judge.contradiction_resolution:.1%} | Active/superseded state checks |",
        f"| Personality consistency | {judge.personality_consistency:.1%} | Forbidden phrase and non-empty checks |",
        f"| Long-range benchmark | {len(long_range.turns)} turns | Synthetic phased test |",
        f"| Oracle key-fact coverage | {oracle.key_fact_coverage:.1%} | Full-memory comparison |",
        f"| Oracle semantic similarity | {oracle.semantic_similarity:.3f} | Local embedding cosine similarity |",
        "",
        "## Pass/Fail Counts",
        "",
        "| Area | Passed | Total | Rate |",
        "|---|---:|---:|---:|",
        f"| Recall | {sum(long_range.recall_checks.values())} | {len(long_range.recall_checks)} | {long_range.recall_score:.1%} |",
        f"| Contradiction | {sum(long_range.contradiction_checks.values())} | {len(long_range.contradiction_checks)} | {long_range.contradiction_score:.1%} |",
        f"| Persona | {sum(long_range.persona_checks.values())} | {len(long_range.persona_checks)} | {long_range.personality_score:.1%} |",
        "",
        "## Failure Examples",
        "",
        "The current benchmark produced no deterministic failures." if all(long_range.recall_checks.values()) and all(long_range.contradiction_checks.values()) else "- See failed checks below.",
    ]
    for checks in (long_range.recall_checks, long_range.contradiction_checks, long_range.persona_checks):
        for name, passed in checks.items():
            if not passed:
                lines.append(f"- `{name}` failed.")
    lines.extend(
        [
            "",
            "## Oracle Comparison",
            "",
            f"Ideal full-memory response: `{oracle.ideal_response}`",
            "",
            f"{oracle.detail}",
            "",
            "## Rubric and Limitations",
            "",
            "- Recall is measured by explicit key-fact coverage, so paraphrases can be marked false negatives.",
            "- Contradiction scoring checks database state and does not prove every generated sentence is factually complete.",
            "- LLM-as-judge scores are supplementary: judges can show positional bias, reward polite tone, miss subtle hallucinations, and vary across models or prompts.",
            "- Embedding similarity is not factual entailment; semantically similar but wrong locations can score well.",
            "- The synthetic benchmark is narrow and self-authored, so it cannot represent real user distributions or adversarial conversations.",
            "- Provider quota, model drift, and heuristic extraction can change live results. CI therefore uses deterministic local embeddings and checks.",
            "",
            "## Scope Boundaries",
            "",
            "- Included: CLI loop, persistent SQLite memory, extraction, retrieval, reconciliation, decay, persona checks, tools, and evaluation.",
            "- Explicitly excluded: UI polish, authentication, billing, multi-user support, voice/image/video generation, production-scale infrastructure, and load testing.",
            "",
            "## Existing Suite",
            "",
            f"The repository evaluator reports {baseline.overall_score:.1%} overall across its existing scenarios.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    long_range = run_long_range_benchmark()
    judge = deterministic_judge(long_range)
    llm_result = llm_judge(long_range)
    if llm_result is not None:
        judge = llm_result
    oracle = oracle_baseline(long_range)
    baseline = Evaluator().run_all()
    RESULTS_PATH.write_text(render_report(long_range, judge, oracle, baseline), encoding="utf-8")
    print(f"Wrote {RESULTS_PATH}")
    print(f"Long-range: {judge.recall_accuracy:.1%} recall, {judge.contradiction_resolution:.1%} contradiction, {judge.personality_consistency:.1%} persona")
    print(f"Oracle: {oracle.key_fact_coverage:.1%} key-fact coverage, {oracle.semantic_similarity:.3f} similarity")


if __name__ == "__main__":
    main()
